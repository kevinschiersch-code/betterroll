// Text in der gewählten Sprache; T("Folge {0}", 5) -> "Folge 5" bzw. "Episode 5"
function T(de, ...args) {
  let s = crlfLang === "en" && Object.prototype.hasOwnProperty.call(CRLF_EN, de) ? CRLF_EN[de] : de;
  if (args.length) s = s.replace(/\{(\d+)\}/g, (m, i) => (args[+i] !== undefined ? String(args[+i]) : m));
  return s;
}

// Zahlen und Datumsangaben passend zur Sprache
function crlfLocale() { return crlfLang === "en" ? "en-US" : "de-DE"; }

// gespeicherte Sprache laden (Design-Skripte laufen schon vor content.js, das die Einstellungen sonst liest)
